"""Regenerates tests/golden_vectors.json from the reference code. Run: python make_golden_vectors.py"""
import json
from rr_reference.pricing import bs_price, bs_greeks, implied_vol, years_from_seconds
from rr_reference.rr import RRParams, compute_rr, scenario_ladder

vectors = {"_note": "Production engine must match within the stated tolerances. Generated by the reference code; "
                    "textbook anchors independently verified with scipy.", "pricing": [], "rr": []}
for S, K, T, sig, c in [(100, 100, 1.0, 0.2, True), (64850.7, 64800, years_from_seconds(85725), 0.45, False),
                        (64850.7, 64800, years_from_seconds(85725), 0.45, True), (65000, 64000, years_from_seconds(7200), 0.6, True)]:
    price = bs_price(S, K, T, sig, c)
    g = bs_greeks(S, K, T, sig, c)
    vectors["pricing"].append({"S": S, "K": K, "T_years": T, "sigma": sig, "is_call": c, "price": price, "greeks": g,
                               "implied_vol_from_price": implied_vol(price, S, K, T, c), "tolerance": {"price_abs": 1e-6, "greeks_rel": 1e-6, "iv_abs": 1e-7}})

p = RRParams(spot=64850.7, strike=64800, is_call=False, seconds_to_expiry=85725, mark=629.0, bid=627.0, ask=631.0,
             sl_spot=65010.0, tp_spot=64560.0, lots=10, hold_seconds=1800)
vectors["rr"].append({"name": "screenshot_put_example", "inputs": p.__dict__ | {"extra": {}},
                      "output": compute_rr(p), "ladder": scenario_ladder(p, [-300, -200, -100, 0, 100, 200]),
                      "tolerance": {"money_abs": 1e-6, "rr_rel": 1e-9}})
json.dump(vectors, open("tests/golden_vectors.json", "w"), indent=2)
r = vectors["rr"][0]["output"]
print(json.dumps(r, indent=2))
for row in vectors["rr"][0]["ladder"]:
    print(row)
